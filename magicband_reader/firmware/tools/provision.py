#!/usr/bin/env python3
"""Writes include/secrets.h with a fresh random 32-byte link key.

    python3 tools/provision.py                 # new key (refuses to overwrite)
    python3 tools/provision.py --force         # replace the key: re-flash BOTH boards
    python3 tools/provision.py --key <64 hex>  # reuse a key you saved elsewhere
    python3 tools/provision.py --show          # print the current key

secrets.h is git-ignored.  Keep a copy of the key in your password manager:
you need it to rebuild either board without re-flashing the other.
"""

import argparse
import os
import re
import secrets
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "include", "secrets.h")

TEMPLATE = """#pragma once
// GENERATED by tools/provision.py -- keep secret, never commit.
// Reader and controller must be built with the same LINK_KEY_HEX.

#define LINK_KEY_HEX "{key}"

// Password for over-the-air updates of the controller (ArduinoOTA).
#define OTA_PASSWORD "{ota}"
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="overwrite an existing secrets.h")
    ap.add_argument("--key", help="use this 64-hex-digit key instead of a random one")
    ap.add_argument("--show", action="store_true", help="print the key in secrets.h and exit")
    a = ap.parse_args()

    if a.show:
        with open(OUT) as f:
            m = re.search(r'LINK_KEY_HEX\s+"([0-9a-fA-F]{64})"', f.read())
        print(m.group(1) if m else "no key found")
        return
    if os.path.exists(OUT) and not a.force:
        sys.exit("include/secrets.h exists; use --force to replace the key (then re-flash BOTH boards)")
    key = a.key or secrets.token_hex(32)
    if not re.fullmatch(r"[0-9a-fA-F]{64}", key):
        sys.exit("--key must be 64 hex digits (32 bytes)")
    with open(OUT, "w") as f:
        f.write(TEMPLATE.format(key=key.lower(), ota=secrets.token_urlsafe(12)))
    os.chmod(OUT, 0o600)
    print("wrote include/secrets.h -- now build and flash both the reader and the controller")


if __name__ == "__main__":
    main()
