#!/usr/bin/env python3
"""Generates test/test_protocol/vectors.h: frames encoded by the Python
implementation (mbproto.py).  The C++ test re-encodes every vector and must
produce identical bytes, and must decode each one back.

    python3 gen_vectors.py          # (re)write the header
    python3 gen_vectors.py --check  # exit 1 if the committed header is stale
"""

import os
import sys

import mbproto as p

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "test", "test_protocol", "vectors.h")

KEY = bytes(range(32))  # test key only, never use on hardware
R, C = p.SRC_READER, p.SRC_CONTROLLER

VECTORS = [
    ("hello_reader", R, p.MSG["HELLO"], 1,
     p.hello(flags=0x06, uptime=42, last_seen=7, fw=(0, 1), caps=p.CAP_FINGERPRINT | p.CAP_NFC)),
    ("hello_reader_nofp", R, p.MSG["HELLO"], 2, p.hello(flags=0x02, uptime=43, last_seen=8, caps=p.CAP_NFC)),
    ("hello_reader_v1", R, p.MSG["HELLO"], 3, p.hello(flags=0x06, uptime=44, last_seen=9, v1=True)),
    ("hello_controller", C, p.MSG["HELLO"], 1, p.hello(flags=0x01, uptime=3600, last_seen=1)),
    ("band_scan_4", R, p.MSG["BAND_SCAN"], 2, p.band_scan(bytes.fromhex("DEADBEEF"))),
    ("band_scan_7", R, p.MSG["BAND_SCAN"], 3, p.band_scan(bytes.fromhex("04A1B2C3D4E5F6"))),
    ("finger_match", R, p.MSG["FINGER_MATCH"], 4, p.finger_match(17, 143)),
    ("finger_nomatch", R, p.MSG["FINGER_NOMATCH"], 5, p.u8(0)),
    ("tamper_open", R, p.MSG["TAMPER"], 6, p.u8(1)),
    ("enroll_result", R, p.MSG["ENROLL_RESULT"], 7, p.enroll_result(3, 0)),
    ("feedback_granted", C, p.MSG["FEEDBACK"], 2, p.feedback("GRANTED", 1500)),
    ("feedback_need_finger", C, p.MSG["FEEDBACK"], 3, p.feedback("NEED_FINGER", 8000)),
    ("enroll_finger", C, p.MSG["ENROLL_FINGER"], 4, p.u16(3)),
    ("set_config", C, p.MSG["SET_CONFIG"], 5, p.set_config(96, 70)),
    ("delete_finger", C, p.MSG["DELETE_FINGER"], 6, p.u16(199)),
    ("big_counter", R, p.MSG["HELLO"], 0xFFFFFFF0, p.hello()),
]


def c_bytes(b):
    return "{" + ", ".join("0x%02X" % x for x in b) + "}" if b else "{0}"


def render():
    lines = [
        "// GENERATED by tools/gen_vectors.py from tools/mbproto.py -- do not edit.",
        "// Frames encoded by the Python implementation; test_protocol checks the",
        "// C++ encoder produces the same bytes and the decoder accepts them.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "static const uint8_t VEC_KEY[32] = %s;" % c_bytes(KEY),
        "",
        "struct Vector {",
        "  const char *name;",
        "  uint8_t src, type;",
        "  uint32_t ctr;",
        "  uint8_t payload[32];",
        "  size_t payloadLen;",
        "  uint8_t frame[56];",
        "  size_t frameLen;",
        "};",
        "",
        "static const Vector VECTORS[] = {",
    ]
    for name, src, mtype, ctr, payload in VECTORS:
        frame = p.encode(KEY, src, mtype, ctr, payload)
        lines.append('    {"%s", 0x%02X, 0x%02X, 0x%08Xu, %s, %d,\n     %s, %d},' % (
            name, src, mtype, ctr, c_bytes(payload), len(payload), c_bytes(frame), len(frame)))
    lines += ["};", "static const size_t VECTOR_COUNT = sizeof(VECTORS) / sizeof(VECTORS[0]);", ""]
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(OUT) as f:
                same = f.read() == text
        except FileNotFoundError:
            same = False
        print("vectors.h up to date" if same else "vectors.h is STALE, run gen_vectors.py")
        sys.exit(0 if same else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (%d vectors)" % (os.path.relpath(OUT), len(VECTORS)))


if __name__ == "__main__":
    main()
